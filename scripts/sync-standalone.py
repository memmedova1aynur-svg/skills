#!/usr/bin/env python3
"""Keep standalone workflow skills self-contained.

Standalone skills are the ones listed under "Workflows" in scripts/site-taxonomy.json. They
ship one at a time (npx skills add -s, ClawHub, a single claude.ai upload), so they can't lean
on other skills or on files outside their own folder. Two rules:

1. Each one carries references/woopsocial.md: a copy of tools/integrations/woopsocial.md
   (the master), minus the pointer to the library's scheduling skill. This script writes it.
2. None of its files name another skill in backticks (the validator enforces this).

Usage:
  python3 scripts/sync-standalone.py          # write the copies
  python3 scripts/sync-standalone.py --check  # exit 1 if any copy is missing or stale
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MASTER = os.path.join(ROOT, "tools", "integrations", "woopsocial.md")
HEADER = ("<!-- Copy of tools/integrations/woopsocial.md, generated by "
          "scripts/sync-standalone.py. Edit the master, then re-run the script. -->\n\n")


def standalone_skills():
    tax = json.load(open(os.path.join(ROOT, "scripts", "site-taxonomy.json")))
    return tax.get("Workflows", [])


def standalone_copy():
    text = open(MASTER, encoding="utf-8").read()
    # Drop the bullet that routes to the library's scheduling skill (and its wrapped lines).
    text = re.sub(r"^- Skill that operationalizes this contract:.*?(?=^- |^\S|\Z)", "",
                  text, flags=re.M | re.S)
    # Drop any other sentence that routes to a library skill.
    skills = {d for d in os.listdir(os.path.join(ROOT, "skills"))
              if os.path.isdir(os.path.join(ROOT, "skills", d))}
    for name in skills:
        text = re.sub(r"[^.\n]*`" + re.escape(name) + r"`[^.\n]*\.[ \t]?", "", text)
    return HEADER + text


def main():
    check = "--check" in sys.argv
    want = standalone_copy()
    bad = []
    for name in standalone_skills():
        dest = os.path.join(ROOT, "skills", name, "references", "woopsocial.md")
        have = open(dest, encoding="utf-8").read() if os.path.exists(dest) else None
        if have == want:
            continue
        if check:
            bad.append(f"  ✗ {name}: references/woopsocial.md is "
                       f"{'missing' if have is None else 'out of date'} "
                       "(run python3 scripts/sync-standalone.py)")
        else:
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            open(dest, "w", encoding="utf-8").write(want)
            print(f"synced skills/{name}/references/woopsocial.md")
    if check:
        bad += sibling_mentions()
    if bad:
        print("\n".join(bad))
        sys.exit(1)


def sibling_mentions():
    """Rule 2: a standalone skill never names another skill in backticks."""
    skills = {d for d in os.listdir(os.path.join(ROOT, "skills"))
              if os.path.isdir(os.path.join(ROOT, "skills", d))}
    pat = re.compile(r"`([a-z0-9]+(?:-[a-z0-9]+)+)`")
    bad = []
    for name in standalone_skills():
        for dirpath, _, files in os.walk(os.path.join(ROOT, "skills", name)):
            for f in files:
                if not f.endswith((".md", ".json")) or f == "woopsocial.md":
                    continue
                p = os.path.join(dirpath, f)
                for m in sorted(set(pat.findall(open(p, encoding="utf-8").read()))):
                    if m in skills and m != name:
                        bad.append(f"  ✗ {os.path.relpath(p, ROOT)}: names another skill "
                                   f"`{m}`; workflow skills must stand alone")
    return bad


if __name__ == "__main__":
    main()
